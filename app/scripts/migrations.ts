// Writes backend/src/migrations.gen.ts from backend/migrations/*.sql. The published backend cannot read files, so
// the SQL ships inside it; the backend applies pending migrations before its first query.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const dir = join(root, 'backend/migrations')
const files = (await readdir(dir)).filter((name) => name.endsWith('.sql')).sort()
const entries = await Promise.all(files.map(async (name) => [name, await readFile(join(dir, name), 'utf8')] as const))

await writeFile(
  join(root, 'backend/src/migrations.gen.ts'),
  `// Generated by scripts/migrations.ts from backend/migrations/. Do not edit.\nexport const migrations: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)}\n`,
)
